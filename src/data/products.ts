/**
 * Fuente: VANTRO Product Database, Capítulos 4-12.
 * Los precios de las presentaciones por peso (500 g / 1 kg / 2 kg) se derivan
 * proporcionalmente del precio oficial por kilogramo documentado. Los productos
 * marcados como "pendiente" o "proximamente" en la Base Oficial NUNCA reciben un
 * precio inventado: su `price` queda en `null` y la interfaz debe mostrar
 * "Consulta disponibilidad" (ver CMS Cap. 11, Microcopys).
 *
 * No existen fotografías reales entregadas todavía (ver Pregunta 2 del análisis
 * de arquitectura). Por eso los productos no incluyen un campo `image`: la UI
 * utiliza un placeholder elegante por categoría de proteína, tal como exige
 * CMS Cap. 18 §11 ("Imagen próximamente").
 */

function kgPresentations(pricePerKg: number) {
  return [
    { label: "500 g", weightGrams: 500, price: Math.round(pricePerKg * 0.5) },
    { label: "1 kg", weightGrams: 1000, price: pricePerKg },
    { label: "2 kg", weightGrams: 2000, price: pricePerKg * 2 },
    { label: "Granel (institucional)", price: null },
  ];
}

function pendingKgPresentations() {
  return [
    { label: "500 g", weightGrams: 500, price: null },
    { label: "1 kg", weightGrams: 1000, price: null },
  ];
}

function burgerPresentations(pricePerUnit: number | null, weightGrams: number) {
  return [
    { label: "Unidad", weightGrams, price: pricePerUnit },
    {
      label: "Paquete x4 und",
      weightGrams: weightGrams * 4,
      price: pricePerUnit ? pricePerUnit * 4 : null,
    },
  ];
}

